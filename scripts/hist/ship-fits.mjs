// Ship walk-forward calibration fits keyed by the first week each may be used (trained strictly before it).
import fs from 'node:fs';
import { fitBudget } from '../../src/calibration.js';
import { fitVolCal } from '../../src/calibration.js';
const raw = s => JSON.parse(fs.readFileSync(`data/hist/raw-${s}.json`)); const bud = s => JSON.parse(fs.readFileSync(`data/hist/budget-${s}.json`));
const R = [2024, 2025, 2026].flatMap(raw), B = [2024, 2025, 2026].flatMap(bud);
const lastW = Math.max(...R.filter(r => r.season === 2026).map(r => r.week));
const fits = [];
for (let w = 1; w <= lastW + 1; w++) { const before = r => r.season < 2026 || r.week < w;
  fits.push({ season: 2026, week: w, budget: fitBudget(R.filter(before)), volcal: fitVolCal(B.filter(before)) }); }
fs.writeFileSync('src/calibration-fits.json', JSON.stringify({ note: 'Walk-forward fits. Entry (season, week) uses only games before that week. Generated by scripts/hist/ship-fits.mjs.', fits }, null, 1));
console.log(fits.map(f => `${f.season}-w${f.week} a=${f.budget.a.toFixed(3)} b=${f.budget.b.toFixed(4)} n=${f.budget.n}`).join('\n'));
